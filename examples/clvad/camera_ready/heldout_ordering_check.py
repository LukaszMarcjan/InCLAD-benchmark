#!/usr/bin/env python3
"""Held-out validation of the InCLAD difficulty orderings.

The published curricula rank concepts by the consensus of PatchCore, PaDiM and
CFA single-task experts. Here an independent difficulty score per concept is
built from the six detectors that played no role in that construction
(GANomaly, STFPM, RD4AD, EfficientAD, PaSTe, FastFlow): the image-level ROC-AUC
on the diagonal of the transition matrix, R[t][t] (performance on a concept
right after learning it), averaged over backbones, orderings and NCL/CL
variants of the runs behind the corrected Table 2. Spearman's rho is computed
between this score and the published consensus score (avg_rank).

Inputs: --aggregates is article_model_aggregates_corrected.json written by
rebuild_main_table.py; --orderings holds <dataset>_easy_to_hard_roc-auc.csv
(the bundle's 02_figure2_ordering/). Defaults derive from --results-root.
"""

from __future__ import annotations

import argparse
import csv
import json
import pathlib
from collections import defaultdict

from scipy.stats import spearmanr

from rebuild_main_table import BUNDLE, REPO_ROOT
from results_root import BUNDLE_NAME, OUTPUT_NAME, add_results_root_argument, require_input, results_root_from_argv

HELD_OUT = ["ganomaly", "stfpm", "rd4ad", "efficientad", "paste", "fastflow"]
DATASETS = ["mpdd", "visa", "mvtec", "dagm", "btech"]
LABEL = {"mvtec": "MVTec AD", "visa": "VisA", "btech": "BTAD", "mpdd": "MPDD", "dagm": "DAGM"}


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_results_root_argument(parser)
    root = results_root_from_argv(argv)
    base = root / OUTPUT_NAME
    parser.add_argument("--aggregates", type=pathlib.Path, default=base / "table2" / "article_model_aggregates_corrected.json")
    parser.add_argument("--orderings", type=pathlib.Path, default=root / BUNDLE_NAME / "02_figure2_ordering")
    parser.add_argument("--output-dir", type=pathlib.Path, default=base / "heldout_ordering")
    return parser.parse_args(argv)


def main() -> int:
    args = parse_args()
    require_input(args.aggregates, "--aggregates")
    require_input(args.orderings, "--orderings")
    aggregates = json.loads(args.aggregates.read_text(encoding="utf-8"))
    diag = defaultdict(lambda: defaultdict(list))
    for record in aggregates["records"]:
        payload = record.get("image")
        if record["model"] not in HELD_OUT or not record.get("article_usable") or not payload or not payload.get("available"):
            continue
        matrix = (payload.get("metric_matrix") or {}).get("mean")
        order = payload.get("concepts_order")
        if not matrix or not order:
            continue
        for index, concept in enumerate(order):
            diag[record["dataset"]][concept].append(matrix[index][index])
    rows = []
    for dataset in DATASETS:
        with (args.orderings / f"{dataset}_easy_to_hard_roc-auc.csv").open(encoding="utf-8") as handle:
            published = {r["concept"]: float(r["avg_rank"]) for r in csv.DictReader(handle)}
        concepts = sorted(published)
        held = [sum(diag[dataset][c]) / len(diag[dataset][c]) for c in concepts]
        rho = spearmanr([published[c] for c in concepts], held).statistic
        rows.append({"dataset": dataset, "concepts": len(concepts), "rho": rho})
    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    (out / "heldout_spearman.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    lines = ["% Auto-generated by examples/clvad/camera_ready/heldout_ordering_check.py", ""]
    for r in rows:
        lines.append(f"{LABEL[r['dataset']]} & {r['concepts']} & {r['rho']:.3f} \\\\")
    mean_rho = sum(r["rho"] for r in rows) / len(rows)
    lines += ["\\midrule", f"Mean &  & {mean_rho:.3f} \\\\"]
    (out / "heldout_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for r in rows:
        print(f"{r['dataset']:6s} n={r['concepts']:2d} rho={r['rho']:.3f}")
    print(f"mean rho={mean_rho:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
